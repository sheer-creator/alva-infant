/**
 * [INPUT]: src/app/components/demo/*.tsx 的 git 创建历史
 * [OUTPUT]: src/data/demo-authors.generated.ts — slug → GitHub login
 * [POS]: 构建脚本 — Demo index 作者署名自动解析（与 Baby 的 generate-demo-index 同逻辑）
 *
 * 产物提交进仓，仅在 predev 时刷新：CI 构建直接用提交的文件，
 * 不依赖 runner 的 git 历史深度与 gh 登录态。
 * slug 约定：组件文件名去掉 Demo 后缀转 kebab-case（AutomationPopoverDemo → automation-popover）。
 */

import { execFile } from 'node:child_process';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const demoDir = path.join(rootDir, 'src/app/components/demo');
const outPath = path.join(rootDir, 'src/data/demo-authors.generated.ts');
const FALLBACK_AUTHOR = 'sheer-creator';

function slugOf(basename) {
  return basename
    .replace(/\.tsx$/, '')
    .replace(/Demo$/, '')
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

async function readExistingAuthors() {
  try {
    const source = await readFile(outPath, 'utf8');
    const match = source.match(/DEMO_AUTHORS[^=]*=\s*(\{[\s\S]*?\})/);
    return match ? JSON.parse(match[1].replace(/'/g, '"').replace(/,\s*\}/, '}')) : {};
  } catch {
    return {};
  }
}

async function gitCreationInfo(repoRelativePath) {
  try {
    const { stdout } = await execFileAsync(
      'git',
      ['log', '--diff-filter=A', '--follow', '--format=%H|%an|%ae', '--', repoRelativePath],
      { cwd: rootDir },
    );
    const lines = stdout.trim().split('\n').filter(Boolean);
    if (lines.length === 0) return null;
    const [sha, name, email] = lines.at(-1).split('|');
    return { sha, name, email };
  } catch {
    return null;
  }
}

const loginCache = new Map();

async function githubLoginFor({ sha, email }) {
  if (loginCache.has(email)) return loginCache.get(email);
  let login = null;
  const noreply = email.match(/^(?:\d+\+)?([A-Za-z0-9-]+)@users\.noreply\.github\.com$/);
  if (noreply) login = noreply[1];
  if (!login) {
    try {
      const { stdout: remote } = await execFileAsync('git', ['remote', 'get-url', 'origin'], { cwd: rootDir });
      const repo = remote.trim().match(/github\.com[/:](?:\d+\/)?([^/]+\/[^/]+?)(?:\.git)?$/)?.[1];
      if (repo) {
        const { stdout } = await execFileAsync('gh', ['api', `repos/${repo}/commits/${sha}`, '--jq', '.author.login // empty']);
        login = stdout.trim() || null;
      }
    } catch {
      // gh 不可用 / 离线：交给调用方决定回退
    }
  }
  if (login) loginCache.set(email, login);
  return login;
}

const existing = await readExistingAuthors();
const entries = (await readdir(demoDir)).filter((name) => name.endsWith('.tsx')).sort();
const authors = {};

for (const file of entries) {
  const slug = slugOf(file);
  const creation = await gitCreationInfo(path.posix.join('src/app/components/demo', file));
  if (!creation) {
    // 尚未提交的新文件归本仓所有者
    authors[slug] = existing[slug] ?? FALLBACK_AUTHOR;
    continue;
  }
  const login = await githubLoginFor(creation);
  // 解析失败时优先沿用上一版已验证的值，最后才退到 git 作者名
  authors[slug] = login ?? existing[slug] ?? creation.name ?? FALLBACK_AUTHOR;
}

const body = Object.entries(authors)
  .map(([slug, author]) => `  '${slug}': '${author}',`)
  .join('\n');

await writeFile(
  outPath,
  `// Auto-generated by scripts/generate-demo-authors.mjs — do not edit by hand.\n// 每个 demo 组件文件的创建者 GitHub login，slug 与 Demo.tsx 中的 DemoSlug 对应。\nexport const DEMO_AUTHORS: Record<string, string> = {\n${body}\n};\n`,
);

console.log(`Generated src/data/demo-authors.generated.ts with ${entries.length} demo${entries.length === 1 ? '' : 's'}:`);
for (const [slug, author] of Object.entries(authors)) console.log(`  ${slug} → @${author}`);
